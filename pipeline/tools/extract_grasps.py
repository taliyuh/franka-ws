"""Regenerate config/grasps.yaml: where each ATB peg sits in the printed fingers.

The printed V-block fingers (franka_fr3_fingers v2) hold every peg off the TCP
axis, at a shape-specific offset and yaw. The nominal CAD grasps
(grasp_poses_v2.json) are registered onto the canonical peg frame by
rl_manip/peg_board_env. Run with that project's interpreter:

    cd <rl_manip checkout>
    PYTHONPATH=. .venv/bin/python <workspace>/pipeline/tools/extract_grasps.py \
        > <workspace>/pipeline/config/grasps.yaml
"""

import json
import math

import numpy as np

from peg_board_env.board_geometry import extract_board_holes, hole_profile
from peg_board_env.build_xml import fit_peg_in_hole
from peg_board_env.gripper import GRASP_KEY, GRASP_POSES_JSON, grasp
from peg_board_env.profiles import nominal_peg_profile, profile_frame, yaw_symmetry_period

HAND_TCP_Z = 0.1034  # panda_hand -> panda_hand_tcp (franka_description)
PEG_LENGTH = 0.050
FLIP = np.diag([1.0, -1.0, -1.0])


def num(value: float, digits: int = 6) -> str:
    return f"{round(value, digits) + 0.0:.{digits}f}"  # + 0.0: no "-0.000000"


print("# Generated by pipeline/tools/extract_grasps.py from the franka_fr3_fingers v2")
print("# grasp_poses_v2.json (nominal CAD values) -- do not edit.")
print("#")
print("# Peg frame: the peg's own hole frame (holes.yaml convention: circle centre /")
print("# polygon area centroid, x = outward normal of the longest flat), origin at the")
print("# peg tip, z along the peg away from the tip. With the peg centred in a hole it")
print("# coincides with that hole's frame, raised to the tip.")
print("#")
print("# shapes.<shape>.tcp: panda_hand_tcp in the peg frame,")
print("#     T_peg_tcp = Trans(x_m, y_m, z_m) @ Rz(yaw_deg) @ Rx(180 deg)")
print("#   yaw_period_deg: peg symmetry; the hand may turn by any multiple (0 = any yaw).")
print("#   grasp_width_mm: gripper width once the peg is seated in the V (+-0.3 mm).")
print("# holes.<hole>: centred peg origin in the hole frame (x_m, y_m). Non-zero only")
print("#   for the L, whose clearance offset moves the polygon centroid.")
entries = json.loads(GRASP_POSES_JSON.read_text())
print("shapes:")
for shape in ("round", "hexagon", "triangle", "rectangle", "l_shape"):
    nominal = nominal_peg_profile(shape)
    origin, yaw = profile_frame(nominal)
    peg = nominal.transformed(origin, yaw)
    hand = grasp(shape, peg, PEG_LENGTH)
    tcp_pos = hand.hand_pos + hand.hand_mat @ np.array([0.0, 0.0, HAND_TCP_Z])
    tcp_mat = hand.hand_mat @ FLIP  # = Rz(yaw), checked below
    tcp_yaw = math.atan2(tcp_mat[1, 0], tcp_mat[0, 0])
    if np.abs(tcp_mat - np.array([[math.cos(tcp_yaw), -math.sin(tcp_yaw), 0.0],
                                  [math.sin(tcp_yaw), math.cos(tcp_yaw), 0.0],
                                  [0.0, 0.0, 1.0]])).max() > 1e-9:
        raise SystemExit(f"{shape}: grasp is not a yaw of the TCP pointing down the peg")
    entry = entries[GRASP_KEY[shape]]
    print(f"  {shape}: {{grasp_width_mm: {entry['expected_width_W_mm']:.3f}, "
          f"yaw_period_deg: {math.degrees(yaw_symmetry_period(peg)):.0f}, "
          f"tcp: {{x_m: {num(tcp_pos[0])}, y_m: {num(tcp_pos[1])}, z_m: {num(tcp_pos[2])}, "
          f"yaw_deg: {num(math.degrees(tcp_yaw), 4)}}}}}")
print("holes:")
for hole in extract_board_holes():
    profile = hole_profile(hole)
    origin, yaw = profile_frame(profile)
    nominal = nominal_peg_profile(hole.shape)
    peg_origin, peg_yaw = profile_frame(nominal)
    fit = fit_peg_in_hole(profile.transformed(origin, yaw), nominal.transformed(peg_origin, peg_yaw))
    centre, centre_yaw = profile_frame(fit.peg)
    if abs(math.remainder(centre_yaw, 2.0 * math.pi)) > 1e-6:
        raise SystemExit(f"{hole.name}: centred peg is turned {math.degrees(centre_yaw):.4f} deg in the hole")
    print(f"  {hole.name}: {{x_m: {num(centre[0])}, y_m: {num(centre[1])}}}")
