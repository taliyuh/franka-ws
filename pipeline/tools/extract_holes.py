"""Regenerate config/holes.yaml from the NIST ATB M1 board STL.

Uses the hole extraction in rl_manip/peg_board_env (slices the STL, fits an
analytic profile per hole). Run with that project's interpreter:

    cd <rl_manip checkout>
    PYTHONPATH=. .venv/bin/python <workspace>/pipeline/tools/extract_holes.py \
        > <workspace>/pipeline/config/holes.yaml
"""

import math

from peg_board_env.board_geometry import BOARD_TOP_Z_CAD, CAD_UNIT_M, extract_board_holes, hole_profile
from peg_board_env.profiles import profile_frame

print("# Generated by pipeline/tools/extract_holes.py from nist_atb_m1.stl -- do not edit.")
print("#")
print("# Board frame: origin at the board centre on the BOTTOM face, z up, so the top")
print("# surface is z = surface_z_m. This is the frame of T_base_board in board_pose.json.")
print("# Columns (x) hold one shape each, rows (y) one clearance class each.")
print("# x_m, y_m: hole frame origin (circle centre / polygon area centroid).")
print("# yaw_deg:  hole frame x axis = outward normal of the longest flat (0 for round).")
print(f"surface_z_m: {BOARD_TOP_Z_CAD * CAD_UNIT_M:.4f}")
print("holes:")
for hole in extract_board_holes():
    origin, yaw = profile_frame(hole_profile(hole))
    print(f"  {hole.name}: {{shape: {hole.shape}, clearance_mm: {hole.clearance_mm:g}, "
          f"x_m: {origin[0]:.6f}, y_m: {origin[1]:.6f}, yaw_deg: {math.degrees(yaw):.2f}}}")
