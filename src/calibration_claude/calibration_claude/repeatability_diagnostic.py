"""Generate and analyze an A/B/A/C/A robot repeatability experiment.

The experiment deliberately uses the cameras as an independent reference:
for repeated A poses, the detected marker corners should return to the same
pixels if the physical tool is repeatable.  The robot FK is reported alongside
that observation, but is not used to decide whether the marker moved.

Examples::

    ros2 run calibration_claude repeatability_diagnostic make-poses \
        --output /franka_ws/repeat_abc_poses.txt

    ros2 run calibration_claude repeatability_diagnostic analyze \
        /franka_ws/session_repeatability_20260910

    ros2 run calibration_claude repeatability_diagnostic make-joint-replay \
        /franka_ws/session_repeatability_20260910 \
        --output /franka_ws/repeat_abc_joints.yaml
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Any

import cv2
import numpy as np
import yaml
from scipy.spatial.transform import Rotation

from . import tag as tag_module
from .solve_handeye import solve_camera_tag_pose, invert


# Values copied from the user's tf2_echo output.  The tf2 display rounds these
# values, so this file is for repeatability diagnosis rather than sub-millimetre
# Cartesian targeting.  The same target is repeated several times, which is the
# important property of the experiment.
DEFAULT_POSES = {
    'A': {
        'translation': [0.436, -0.027, 0.280],
        'quaternion_xyzw': [0.985, -0.016, 0.165, 0.042],
    },
    'B': {
        'translation': [0.391, -0.189, 0.267],
        'quaternion_xyzw': [0.988, 0.022, 0.129, 0.078],
    },
    'C': {
        'translation': [0.368, 0.147, 0.234],
        'quaternion_xyzw': [0.977, -0.178, 0.111, -0.040],
    },
}

DEFAULT_SEQUENCE = ('A', 'B', 'A', 'C', 'A', 'B', 'A', 'C', 'A')


def _normalised_quaternion(values: list[float]) -> np.ndarray:
    quaternion = np.asarray(values, dtype=float)
    norm = np.linalg.norm(quaternion)
    if quaternion.shape != (4,) or not np.isfinite(quaternion).all() or norm <= 1e-12:
        raise ValueError('quaternion must contain four finite non-zero values')
    return quaternion / norm


def _format_vector(values: list[float] | np.ndarray) -> str:
    return ', '.join(f'{float(value):.9f}' for value in values)


def make_poses(output: Path, sequence: tuple[str, ...]) -> None:
    """Write a taught-capture Cartesian pose file for *sequence*."""
    unknown = sorted(set(sequence) - set(DEFAULT_POSES))
    if unknown:
        raise ValueError(f'unknown pose labels: {unknown}')
    output.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        '# Generated by calibration_claude repeatability_diagnostic.',
        '# The sequence is intentionally A/B/A/C/A/... .',
    ]
    for index, label in enumerate(sequence, start=1):
        pose = DEFAULT_POSES[label]
        lines.extend([
            f'pose {index}:  # {label}',
            f'Translation: [{_format_vector(pose["translation"])}]',
            'Quaternion (xyzw) '
            f'[{_format_vector(_normalised_quaternion(pose["quaternion_xyzw"]))}]',
            '',
        ])
    output.write_text('\n'.join(lines), encoding='utf-8')

    sidecar = output.with_suffix(output.suffix + '.json')
    sidecar.write_text(json.dumps({
        'sequence': list(sequence),
        'poses': DEFAULT_POSES,
    }, indent=2) + '\n', encoding='utf-8')


def make_joint_replay(session: Path, output: Path,
                      sequence: tuple[str, ...]) -> None:
    """Export measured A/B/C joints from a first run for exact replay.

    The first Cartesian run establishes safe, reachable joint solutions.  This
    second file is consumed by ``run_calibration_capture --reuse`` and removes
    any ambiguity from solving the repeated Cartesian A pose through IK.
    """
    manifest_path = session / 'poses.yaml'
    manifest = yaml.safe_load(manifest_path.read_text(encoding='utf-8')) or {}
    poses = sorted(manifest.get('poses', []), key=lambda pose: int(pose['index']))
    if len(poses) < len(sequence):
        raise ValueError(f'{manifest_path} contains only {len(poses)} poses; '
                         f'need {len(sequence)}')
    by_label: dict[str, list[float]] = {}
    joint_names = None
    for label, pose in zip(sequence, poses):
        if 'measured_joints' not in pose:
            raise ValueError(f'pose {pose.get("index", "?")}: missing measured_joints')
        if label not in by_label:
            by_label[label] = [float(value) for value in pose['measured_joints']]
        joint_names = joint_names or pose.get('joint_names')
    if not joint_names:
        joint_names = [f'fr3_joint{index}' for index in range(1, 8)]
    output.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        'joint_names': joint_names,
        'sequence': list(sequence),
        'poses': [{'joints': by_label[label]} for label in sequence],
    }
    output.write_text(yaml.safe_dump(payload, sort_keys=False), encoding='utf-8')


def _matrix_from_record(record: dict[str, Any]) -> np.ndarray:
    matrix = np.asarray(record['matrix'], dtype=float)
    if matrix.shape != (4, 4):
        raise ValueError('T_base_tcp must be a 4x4 matrix')
    return matrix


def _rotation_delta_deg(first: np.ndarray, second: np.ndarray) -> float:
    relative = first[:3, :3].T @ second[:3, :3]
    return float(np.degrees(Rotation.from_matrix(relative).magnitude()))


def _transform_delta(first: np.ndarray, second: np.ndarray) -> dict[str, float]:
    relative = invert(first) @ second
    return {
        'translation_mm': float(np.linalg.norm(relative[:3, 3]) * 1000.0),
        'rotation_deg': _rotation_delta_deg(first, second),
    }


def _corner_delta(first: np.ndarray, second: np.ndarray) -> dict[str, float]:
    delta = np.asarray(first, dtype=float) - np.asarray(second, dtype=float)
    distances = np.linalg.norm(delta, axis=1)
    return {
        'rms_px': float(np.sqrt(np.mean(distances ** 2))),
        'max_px': float(np.max(distances)),
    }


def _load_observations(session: Path) -> tuple[dict[str, Any], dict[str, list[dict[str, Any]]]]:
    manifest_path = session / 'poses.yaml'
    if not manifest_path.exists():
        raise ValueError(f'missing {manifest_path}')
    manifest = yaml.safe_load(manifest_path.read_text(encoding='utf-8')) or {}
    poses = sorted(manifest.get('poses', []), key=lambda pose: int(pose['index']))
    if not poses:
        raise ValueError('poses.yaml contains no poses')

    meta_path = session / 'meta.yaml'
    meta = yaml.safe_load(meta_path.read_text(encoding='utf-8')) if meta_path.exists() else {}
    meta = meta or {}
    tag_config = meta.get('tag', {})
    tag_size = float(tag_config.get('size', 0.106))
    tag_id = int(tag_config.get('id', 0))
    tag_family = str(tag_config.get('family', '4x4_50'))
    detection_manifest_path = session / 'detections.yaml'
    detection_manifest = (
        yaml.safe_load(detection_manifest_path.read_text(encoding='utf-8'))
        if detection_manifest_path.exists() else {}
    ) or {}
    detections_by_index = {
        int(pose['index']): pose.get('cameras', {})
        for pose in detection_manifest.get('poses', [])
    }
    meta_camera_info = meta.get('cameras', {})

    samples: dict[str, list[dict[str, Any]]] = {}
    for pose in poses:
        base_tcp = _matrix_from_record(pose['T_base_tcp'])
        pose_index = int(pose['index'])
        image_paths = dict(pose.get('images', {}))
        for camera, entry in detections_by_index.get(pose_index, {}).items():
            if isinstance(entry, dict) and entry.get('image'):
                image_paths.setdefault(camera, entry['image'])
        if not image_paths:
            raise ValueError(f'pose {pose_index}: no camera image paths found')
        for camera, image_path in sorted(image_paths.items()):
            image = cv2.imread(str(session / image_path))
            if image is None:
                raise ValueError(f'could not read {session / image_path}')
            detection = tag_module.detect(image, tag_id, tag_family)
            if not detection.detected or detection.corners is None:
                samples.setdefault(camera, []).append({
                    'index': pose_index,
                    'base_tcp': base_tcp,
                    'detected': False,
                })
                continue
            camera_info = pose.get('cameras', {}).get(camera) or meta_camera_info.get(camera)
            if not camera_info:
                raise ValueError(f'pose {pose_index}, {camera}: missing camera info')
            camera_tag, pnp_rms = solve_camera_tag_pose(
                detection.corners, camera_info, tag_size)
            samples.setdefault(camera, []).append({
                'index': pose_index,
                'base_tcp': base_tcp,
                'q': np.asarray(pose['measured_joints'], dtype=float),
                'corners': np.asarray(detection.corners, dtype=float),
                'camera_tag': camera_tag,
                'pnp_rms_px': pnp_rms,
                'detected': True,
            })
    return manifest, samples


def analyze(session: Path, sequence: tuple[str, ...], output: Path | None,
            max_q_delta_deg: float, max_corner_rms_px: float) -> int:
    manifest, samples = _load_observations(session)
    ordered_poses = sorted(
        manifest.get('poses', []), key=lambda pose: int(pose['index'])
    )
    if len(ordered_poses) < len(sequence):
        raise ValueError(
            f'manifest contains {len(ordered_poses)} poses; '
            f'need at least {len(sequence)}'
        )
    # Generated captures number poses from zero, while taught captures number
    # them from one.  Sequence position is the stable identity for this test;
    # the original manifest index is retained in the report for traceability.
    poses_by_position = {
        position: pose
        for position, pose in enumerate(ordered_poses[:len(sequence)])
    }
    a_positions = [
        position for position, label in enumerate(sequence) if label == 'A'
    ]
    if len(a_positions) < 2:
        raise ValueError('sequence must contain at least two A poses')

    pairs = []
    for occurrence, current_position in enumerate(a_positions[1:], start=1):
        previous_position = a_positions[occurrence - 1]
        route = sequence[current_position - 1] if current_position >= 1 else 'unknown'
        first_pose = poses_by_position[previous_position]
        second_pose = poses_by_position[current_position]
        first_index = int(first_pose['index'])
        second_index = int(second_pose['index'])
        q_first = np.asarray(first_pose['measured_joints'], dtype=float)
        q_second = np.asarray(second_pose['measured_joints'], dtype=float)
        pair: dict[str, Any] = {
            'first_index': first_index,
            'second_index': second_index,
            'return_route': route,
            'max_joint_delta_deg': float(np.max(np.degrees(np.abs(q_first - q_second)))),
            'tcp_delta': _transform_delta(
                _matrix_from_record(first_pose['T_base_tcp']),
                _matrix_from_record(second_pose['T_base_tcp']),
            ),
            'cameras': {},
        }
        for camera, camera_samples in sorted(samples.items()):
            by_index = {sample['index']: sample for sample in camera_samples}
            first = by_index.get(first_index)
            second = by_index.get(second_index)
            camera_result: dict[str, Any] = {}
            if not first or not second or not first.get('detected') or not second.get('detected'):
                camera_result['status'] = 'undetected'
            else:
                camera_result['status'] = 'ok'
                camera_result['corner_delta'] = _corner_delta(
                    first['corners'], second['corners'])
                camera_result['pnp_delta'] = _transform_delta(
                    first['camera_tag'], second['camera_tag'])
                camera_result['tcp_camera_rotation_difference_deg'] = abs(
                    camera_result['pnp_delta']['rotation_deg']
                    - pair['tcp_delta']['rotation_deg']
                )
                camera_result['pnp_rms_px'] = {
                    'first': float(first['pnp_rms_px']),
                    'second': float(second['pnp_rms_px']),
                }
            pair['cameras'][camera] = camera_result
        pairs.append(pair)

    camera_names = sorted(samples)
    repeatable_robot = all(pair['max_joint_delta_deg'] <= max_q_delta_deg for pair in pairs)
    corner_values = [
        pair['cameras'][camera]['corner_delta']['rms_px']
        for pair in pairs for camera in camera_names
        if pair['cameras'][camera].get('status') == 'ok'
    ]
    all_cameras_repeat = bool(corner_values) and all(
        value <= max_corner_rms_px for value in corner_values)
    rotation_consistency_values = [
        pair['cameras'][camera]['tcp_camera_rotation_difference_deg']
        for pair in pairs for camera in camera_names
        if pair['cameras'][camera].get('status') == 'ok'
    ]
    camera_tracks_tcp = bool(rotation_consistency_values) and all(
        value <= 0.15 for value in rotation_consistency_values)
    if not repeatable_robot and camera_tracks_tcp:
        conclusion = (
            'inconclusive target return: exact joint targets were commanded, but the settled '
            'measured TCP still differs; marker motion tracks that TCP motion, so fix '
            'position tracking/load compensation before diagnosing gripper slip'
        )
    elif not repeatable_robot:
        conclusion = 'inconclusive: repeated A targets did not return to the same measured joints'
    elif all_cameras_repeat:
        conclusion = (
            'marker repeatability is good; remaining calibration error is likely a repeatable '
            'robot/tool kinematic-model discrepancy'
        )
    else:
        conclusion = (
            'marker repeatability is poor after returning to the same joints; investigate '
            'gripper/plate flex, slip, backlash, or unconfigured tool load'
        )

    report = {
        'session': str(session),
        'sequence': list(sequence),
        'thresholds': {
            'max_joint_delta_deg': max_q_delta_deg,
            'max_corner_rms_px': max_corner_rms_px,
        },
        'conclusion': conclusion,
        'pairs': pairs,
    }
    report_path = output or session / 'repeatability_report.json'
    report_path.write_text(json.dumps(report, indent=2, default=_json_default) + '\n', encoding='utf-8')

    print(f'session: {session}')
    print(f'conclusion: {conclusion}')
    for pair in pairs:
        print(
            f'A{pair["first_index"]}->A{pair["second_index"]} '
            f'(via {pair["return_route"]}): '
            f'max joint delta {pair["max_joint_delta_deg"]:.3f} deg, '
            f'TCP delta {pair["tcp_delta"]["translation_mm"]:.2f} mm / '
            f'{pair["tcp_delta"]["rotation_deg"]:.3f} deg')
        for camera in camera_names:
            result = pair['cameras'][camera]
            if result.get('status') != 'ok':
                print(f'  {camera}: tag not detected in both images')
                continue
            print(
                f'  {camera}: corners {result["corner_delta"]["rms_px"]:.2f} px RMS, '
                f'{result["corner_delta"]["max_px"]:.2f} px max; '
                f'PnP {result["pnp_delta"]["translation_mm"]:.2f} mm / '
                f'{result["pnp_delta"]["rotation_deg"]:.3f} deg; '
                f'camera/TCP rotation difference '
                f'{result["tcp_camera_rotation_difference_deg"]:.3f} deg')
    print(f'report: {report_path}')
    return 0


def _json_default(value: Any) -> Any:
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, np.generic):
        return value.item()
    raise TypeError(f'cannot serialize {type(value).__name__}')


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest='command', required=True)

    make_parser = subparsers.add_parser('make-poses', help='write the repeated Cartesian pose file')
    make_parser.add_argument('--output', type=Path, required=True)
    make_parser.add_argument('--sequence', default=','.join(DEFAULT_SEQUENCE))

    replay_parser = subparsers.add_parser(
        'make-joint-replay',
        help='export measured joint vectors from a first Cartesian run',
    )
    replay_parser.add_argument('session', type=Path)
    replay_parser.add_argument('--output', type=Path, required=True)
    replay_parser.add_argument('--sequence', default=','.join(DEFAULT_SEQUENCE))

    analyze_parser = subparsers.add_parser('analyze', help='analyze a captured repeatability session')
    analyze_parser.add_argument('session', type=Path)
    analyze_parser.add_argument('--sequence', default=','.join(DEFAULT_SEQUENCE))
    analyze_parser.add_argument('--output', type=Path)
    analyze_parser.add_argument('--max-q-delta-deg', type=float, default=0.2)
    analyze_parser.add_argument('--max-corner-rms-px', type=float, default=2.0)

    args = parser.parse_args(argv)
    sequence = tuple(label.strip().upper() for label in args.sequence.split(',') if label.strip())
    if not sequence:
        parser.error('sequence cannot be empty')
    try:
        if args.command == 'make-poses':
            make_poses(args.output, sequence)
            print(f'wrote {args.output}')
            print(f'wrote {args.output.with_suffix(args.output.suffix + ".json")}')
            return 0
        if args.command == 'make-joint-replay':
            make_joint_replay(args.session, args.output, sequence)
            print(f'wrote {args.output}')
            return 0
        return analyze(args.session, sequence, args.output,
                       args.max_q_delta_deg, args.max_corner_rms_px)
    except (OSError, ValueError, KeyError, yaml.YAMLError) as error:
        print(f'error: {error}', file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
